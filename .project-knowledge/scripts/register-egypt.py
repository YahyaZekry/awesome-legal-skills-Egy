def render(name: str, category: str, description: str) -> str:
    """Render one plugin entry in the upstream formatting exactly."""
    skills = f'["./skills/{name}", "./skills/{name}-ar"]'
    lines = [
        "    {",
        f'      "name": {json.dumps(name, ensure_ascii=False)},',
        '      "source": "./",',
        f'      "description": {json.dumps(description, ensure_ascii=False)},',
        f'      "version": {json.dumps(VERSION)},',
        '      "author": {',
        f'        "name": {json.dumps(AUTHOR, ensure_ascii=False)}',
        "      },",
        f'      "license": {json.dumps(LICENSE)},',
        f'      "category": {json.dumps(category, ensure_ascii=False)},',
        f'      "skills": {skills},',
        '      "strict": false',
        "    }",
    ]
    return "\n".join(lines)


def verify_skill_dirs_exist() -> list[str]:
    """A plugin pointing at a missing directory installs as a broken plugin."""
    missing = []
    for name, _cat, _desc in PLUGINS:
        for suffix in ("", "-ar"):
            if not (REPO / "skills" / f"{name}{suffix}" / "SKILL.md").is_file():
                missing.append(f"skills/{name}{suffix}")
    return missing


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="report without writing")
    args = ap.parse_args()

    missing = verify_skill_dirs_exist()
    if missing:
        print("ERROR — these skill directories do not exist:", file=sys.stderr)
        for m in missing:
            print(f"  {m}", file=sys.stderr)
        return 2

    raw = MARKETPLACE.read_text(encoding="utf-8")

    # Sanity: the file must parse before we touch it.
    json.loads(raw)

    if not raw.endswith(TAIL):
        print(
            f"ERROR — {MARKETPLACE.name} does not end with the expected structure.\n"
            f"Expected to end with: {TAIL!r}\n"
            "The upstream format may have changed. Inspect the file before editing.",
            file=sys.stderr,
        )
        return 3

    body = raw[: -len(TAIL)]

    # Idempotency: drop any Egypt block already present at the tail.
    had_previous = False
    idx = EXISTING_EGYPT.search(body)
    if idx:
        # idx.start() sits on the newline *before* the entry, so the comma that
        # separated the last upstream entry is left dangling on the end of body.
        # Strip it, or the rebuild emits a double comma.
        body = body[: idx.start()].rstrip()
        if body.endswith(","):
            body = body[:-1]
        had_previous = True

    entries = ",\n".join(render(*p) for p in PLUGINS)
    new_raw = body + ",\n" + entries + TAIL

    original = json.loads(raw)
    parsed = json.loads(new_raw)

    # The invariant that matters: every upstream entry survives untouched, in
    # order, and exactly the Egypt entries are added. Comparing non-Egypt names
    # makes this work whether or not a previous Egypt block was present.
    orig_non_egypt = [p["name"] for p in original["plugins"] if not p["name"].startswith("egy-")]
    new_non_egypt = [p["name"] for p in parsed["plugins"] if not p["name"].startswith("egy-")]
    if new_non_egypt != orig_non_egypt:
        print("ERROR — upstream entries were altered. Aborting.", file=sys.stderr)
        return 5

    names = [p["name"] for p in parsed["plugins"]]
    if len(names) != len(set(names)):
        dupes = sorted({n for n in names if names.count(n) > 1})
        print(f"ERROR — duplicate plugin names would result: {dupes}", file=sys.stderr)
        return 4

    egy_names = [n for n in names if n.startswith("egy-")]
    if len(egy_names) != len(PLUGINS):
        print(
            f"ERROR — expected {len(PLUGINS)} Egypt plugins, got {len(egy_names)}: {egy_names}",
            file=sys.stderr,
        )
        return 6

    for name, _c, _d in PLUGINS:
        entry = next(p for p in parsed["plugins"] if p["name"] == name)
        if entry["skills"] != [f"./skills/{name}", f"./skills/{name}-ar"]:
            print(f"ERROR — bad skills array on {name}", file=sys.stderr)
            return 6

    if had_previous:
        print("replaced the existing Egypt block (idempotent re-run)")
    else:
        print("no Egypt entries were present — appending fresh")

    print(f"upstream plugins preserved: {len(orig_non_egypt)}")
    print(f"Egypt plugins:              {len(egy_names)}")
    print(f"total:                      {len(names)}")
    print("valid JSON, no duplicates, upstream order intact, skill dirs exist")

    if args.check:
        print("\n--check: not written")
        return 0

    MARKETPLACE.write_text(new_raw, encoding="utf-8")
    print(f"wrote {MARKETPLACE.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
