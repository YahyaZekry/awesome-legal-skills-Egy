#!/usr/bin/env python3
"""
Register the Egypt Edition skills in .claude-plugin/marketplace.json.

WHY THIS SCRIPT EXISTS
----------------------
The 24 Egypt skills (12 topics x EN/AR) live in `skills/egy-*` and are otherwise
invisible: `marketplace.json` is generated upstream and contains no Egypt entries.

That file is regenerated by the Lawve sync, which reaches this fork by merging
`upstream/main`. So any hand-edit will eventually be lost or conflict. This script
is **idempotent** — re-run it after every merge and the entries come back in the
right place with no duplicates.

    python3 .project-knowledge/scripts/register-egypt.py [--check]

`--check` reports what would change without writing.

WHY IT EDITS TEXT INSTEAD OF ROUND-TRIPPING JSON
------------------------------------------------
`json.dumps(data, indent=2)` does NOT reproduce the upstream file (it emits
~243 KB where the original is ~235 KB — the real file keeps `skills` arrays
inline). A round-trip would therefore reformat all 264 upstream entries and
produce a 3000-line diff for a 12-entry change.

Instead this injects the entries textually immediately before the array's closing
bracket, matching the observed formatting exactly:
  4-space `{`, 6-space keys, 8-space nested `author.name`,
  inline `skills` array, raw UTF-8.
"""

